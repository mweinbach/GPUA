/// macOS `PlatformKeyboardLayout` queried via Carbon `TISCopyCurrentKeyboardLayoutInputSource`.
public struct MacKeyboardLayout: PlatformKeyboardLayout, Sendable {
    public let id: String
    public let name: String

    public init(id: String, name: String) {
        self.id = id
        self.name = name
    }

    public static func new() -> MacKeyboardLayout {
        guard let source = copyCurrentKeyboardLayoutInputSource() else {
            return MacKeyboardLayout(id: "com.apple.keylayout.US", name: "U.S.")
        }
        let id = inputSourceStringProperty(source, kTISPropertyInputSourceID) ?? "com.apple.keylayout.US"
        let name = inputSourceStringProperty(source, kTISPropertyLocalizedName) ?? "U.S."
        return MacKeyboardLayout(id: id, name: name)
    }
}

/// macOS `PlatformKeyboardMapper` applying Apple's localized Command-shortcut key equivalents.
public struct MacKeyboardMapper: PlatformKeyboardMapper, Sendable {
    private let keyEquivalents: [Character: Character]?

    public init(layoutId: String) {
        self.keyEquivalents = GPUIMacOS.getKeyEquivalents(layoutId)
    }

    public static func new(_ layoutId: String) -> MacKeyboardMapper {
        MacKeyboardMapper(layoutId: layoutId)
    }

    public func mapKeyEquivalent(
        keystroke: Keystroke,
        useKeyEquivalents: Bool
    ) -> KeybindingKeystroke {
        var mapped = keystroke
        if useKeyEquivalents,
           let equivalents = keyEquivalents,
           mapped.key.count == 1,
           let firstChar = mapped.key.first,
           let replacement = equivalents[firstChar]
        {
            mapped.key = String(replacement)
        }
        return KeybindingKeystroke.fromKeystroke(mapped)
    }

    public func getKeyEquivalents() -> [Character: Character]? {
        keyEquivalents
    }
}

