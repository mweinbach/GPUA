/// The auto-repeat fit strategy to use
public enum AutoRepeatStrategy: Sendable, Hashable {
    /// If the grid container has a definite size or max size in the relevant axis:
    ///   - then the number of repetitions is the largest possible positive integer that does not cause the grid to overflow the content
    ///     box of its grid container.
    case maxRepetitionsThatDoNotOverflow
    /// Otherwise, if the grid container has a definite min size in the relevant axis:
    ///   - then the number of repetitions is the smallest possible positive integer that fulfills that minimum requirement
    case minRepetitionsThatDoOverflow
}

/// Compute the number of rows and columns in the explicit grid
public func computeExplicitGridSizeInAxis<StyleType: GridContainerStyle>(
    style: StyleType,
    autoFitContainerSize: Float?,
    autoFitStrategy: AutoRepeatStrategy,
    resolveCalcValue: (UnsafeRawPointer?, Float) -> Float,
    axis: AbsoluteAxis
) -> (numRepetitions: UInt16, gridTemplateTrackCount: UInt16) {
    let template: [GridTemplateComponent<StyleType.CustomIdent>] = {
        switch axis {
        case .horizontal: return style.gridTemplateColumns
        case .vertical: return style.gridTemplateRows
        }
    }()

    if template.isEmpty {
        return (0, 0)
    }

    // If there are any repetitions that contains no tracks, then the whole definition should be considered invalid
    // and we default to no explicit tracks
    let templateHasRepetitionsWithZeroTracks = template.contains { trackDef in
        switch trackDef {
        case .single: return false
        case .repeat_(let rep): return rep.trackCount == 0
        }
    }
    if templateHasRepetitionsWithZeroTracks {
        return (0, 0)
    }

    // Compute that number of tracks generated by single track definition and repetitions with a fixed repetition count
    var nonAutoRepeatingTrackCount: UInt16 = 0
    for trackDef in template {
        switch trackDef {
        case .single:
            nonAutoRepeatingTrackCount += 1
        case .repeat_(let rep):
            switch rep.count {
            case .count(let count):
                nonAutoRepeatingTrackCount += count * rep.trackCount
            case .autoFit, .autoFill:
                break
            }
        }
    }

    let autoRepetitionCount = template.filter { $0.isAutoRepetition }.count
    let allTrackDefsHaveFixedComponent = template.allSatisfy { trackDef in
        switch trackDef {
        case .single(let fn):
            return fn.hasFixedComponent()
        case .repeat_(let rep):
            return rep.tracks.allSatisfy { $0.hasFixedComponent() }
        }
    }

    let templateIsValid = autoRepetitionCount == 0 || (autoRepetitionCount == 1 && allTrackDefsHaveFixedComponent)

    // If the template is invalid because it contains multiple auto-repetition definitions or it combines an auto-repetition
    // definition with non-fixed-size track sizing functions, then disregard it entirely and default to zero explicit tracks
    if !templateIsValid {
        return (0, 0)
    }

    // If there are no repetitions, then the number of explicit tracks is simply equal to the length
    if autoRepetitionCount == 0 {
        return (0, nonAutoRepeatingTrackCount)
    }

    guard let repDef = template.compactMap({ def -> GridTemplateRepetition<StyleType.CustomIdent>? in
        switch def {
        case .single: return nil
        case .repeat_(let rep):
            switch rep.count {
            case .count: return nil
            case .autoFit, .autoFill: return rep
            }
        }
    }).first else {
        return (0, nonAutoRepeatingTrackCount)
    }

    let repetitionTrackCount = repDef.trackCount

    func trackDefiniteValue(_ sizingFunction: TrackSizingFunction, _ parentSize: Float?) -> Float {
        let maxSize = sizingFunction.max.definiteValue(parentSize: parentSize)
        let minSize = sizingFunction.min.definiteValue(parentSize: parentSize)
        if let mx = maxSize {
            return mx.maybeMax(minSize)
        } else {
            return minSize!
        }
    }

    // Determine the number of repetitions
    let numRepetitions: UInt16 = {
        guard let innerContainerSize = autoFitContainerSize else {
            return 1
        }
        let parentSize: Float? = innerContainerSize

        var nonRepeatingTrackUsedSpace: Float = 0.0
        for trackDef in template {
            switch trackDef {
            case .single(let sizingFunction):
                nonRepeatingTrackUsedSpace += trackDefiniteValue(sizingFunction, parentSize)
            case .repeat_(let rep):
                switch rep.count {
                case .count(let count):
                    let sum = rep.tracks.reduce(0.0) { $0 + trackDefiniteValue($1, parentSize) }
                    nonRepeatingTrackUsedSpace += sum * Float(count)
                case .autoFit, .autoFill:
                    break
                }
            }
        }

        let gap = axis == .horizontal ? style.gap.width : style.gap.height
        let gapSize = gap.resolveOrZero(innerContainerSize) { resolveCalcValue($0, $1) }

        let perRepetitionTrackUsedSpace = repDef.tracks.reduce(0.0) { $0 + trackDefiniteValue($1, parentSize) }

        let firstRepetitionAndNonRepeatingTracksUsedSpace = nonRepeatingTrackUsedSpace
            + perRepetitionTrackUsedSpace
            + (Float(Swift.max(Int(nonAutoRepeatingTrackCount + repetitionTrackCount) - 1, 0)) * gapSize)

        if firstRepetitionAndNonRepeatingTracksUsedSpace > innerContainerSize {
            return 1
        } else {
            let perRepetitionGapUsedSpace = Float(repetitionTrackCount) * gapSize
            let perRepetitionUsedSpace = perRepetitionTrackUsedSpace + perRepetitionGapUsedSpace
            let numRepetitionThatFit = (innerContainerSize - firstRepetitionAndNonRepeatingTracksUsedSpace) / perRepetitionUsedSpace

            switch autoFitStrategy {
            case .maxRepetitionsThatDoNotOverflow:
                return UInt16(floor(numRepetitionThatFit)) + 1
            case .minRepetitionsThatDoOverflow:
                return UInt16(ceil(numRepetitionThatFit)) + 1
            }
        }
    }()

    let gridTemplateTrackCount = nonAutoRepeatingTrackCount + (repetitionTrackCount * numRepetitions)
    return (numRepetitions, gridTemplateTrackCount)
}

/// Utility function for repeating logic of creating implicit tracks
private func createImplicitTracks(
    tracks: inout [GridTrack],
    count: UInt16,
    autoTracks: [TrackSizingFunction],
    gap: LengthPercentage,
    offset: Int = 0
) {
    if autoTracks.isEmpty {
        for _ in 0..<count {
            tracks.append(GridTrack.new(
                minTrackSizingFunction: TrackSizingFunction.AUTO.min,
                maxTrackSizingFunction: TrackSizingFunction.AUTO.max
            ))
            tracks.append(GridTrack.gutter(size: gap))
        }
    } else {
        let n = autoTracks.count
        for i in 0..<Int(count) {
            let trackDef = autoTracks[(offset + i) % n]
            tracks.append(GridTrack.new(
                minTrackSizingFunction: trackDef.min,
                maxTrackSizingFunction: trackDef.max
            ))
            tracks.append(GridTrack.gutter(size: gap))
        }
    }
}

/// Resolve the track sizing functions of explicit tracks, automatically created tracks, and gutters
public func initializeGridTracks<StyleType: GridContainerStyle>(
    tracks: inout [GridTrack],
    counts: TrackCounts,
    style: StyleType,
    axis: AbsoluteAxis,
    trackHasItems: (Int) -> Bool
) {
    let trackTemplate: [GridTemplateComponent<StyleType.CustomIdent>]
    let autoTracks: [TrackSizingFunction]
    let gap: LengthPercentage
    switch axis {
    case .horizontal:
        trackTemplate = style.gridTemplateColumns
        autoTracks = style.gridAutoColumns
        gap = style.gap.width
    case .vertical:
        trackTemplate = style.gridTemplateRows
        autoTracks = style.gridAutoRows
        gap = style.gap.height
    }

    tracks.removeAll(keepingCapacity: true)
    tracks.reserveCapacity((counts.len() * 2) + 1)
    tracks.append(GridTrack.gutter(size: gap))

    let autoTrackCount = autoTracks.count

    // Create negative implicit tracks
    if counts.negativeImplicit > 0 {
        if autoTrackCount == 0 {
            createImplicitTracks(tracks: &tracks, count: counts.negativeImplicit, autoTracks: [], gap: gap)
        } else {
            let offset = autoTrackCount - (Int(counts.negativeImplicit) % autoTrackCount)
            createImplicitTracks(tracks: &tracks, count: counts.negativeImplicit, autoTracks: autoTracks, gap: gap, offset: offset)
        }
    }

    var currentTrackIndex = Int(counts.negativeImplicit)

    // Create explicit tracks
    if counts.explicit > 0 && !trackTemplate.isEmpty {
        for trackSizingFunction in trackTemplate {
            switch trackSizingFunction {
            case .single(let sizingFunction):
                tracks.append(GridTrack.new(
                    minTrackSizingFunction: sizingFunction.min,
                    maxTrackSizingFunction: sizingFunction.max
                ))
                tracks.append(GridTrack.gutter(size: gap))
                currentTrackIndex += 1
            case .repeat_(let rep):
                switch rep.count {
                case .count(let count):
                    for _ in 0..<count {
                        for sizingFunction in rep.tracks {
                            tracks.append(GridTrack.new(
                                minTrackSizingFunction: sizingFunction.min,
                                maxTrackSizingFunction: sizingFunction.max
                            ))
                            tracks.append(GridTrack.gutter(size: gap))
                            currentTrackIndex += 1
                        }
                    }
                case .autoFit, .autoFill:
                    let autoRepeatedTrackCount = Int(counts.explicit) - (trackTemplate.count - 1)
                    let n = rep.tracks.count
                    for i in 0..<autoRepeatedTrackCount {
                        let trackDef = rep.tracks[i % n]
                        var track = GridTrack.new(
                            minTrackSizingFunction: trackDef.min,
                            maxTrackSizingFunction: trackDef.max
                        )
                        var gutter = GridTrack.gutter(size: gap)

                        if rep.count == .autoFit && !trackHasItems(currentTrackIndex) {
                            track.collapse()
                            gutter.collapse()
                        }

                        tracks.append(track)
                        tracks.append(gutter)
                        currentTrackIndex += 1
                    }
                }
            }
        }
    }

    let gridAreaTracks = Int(counts.negativeImplicit + counts.explicit) - currentTrackIndex

    // Create positive implicit tracks
    let positiveCount = UInt16(Swift.max(Int(counts.positiveImplicit) + gridAreaTracks, 0))
    createImplicitTracks(tracks: &tracks, count: positiveCount, autoTracks: autoTracks, gap: gap)

    // Mark first and last grid lines as collapsed
    if !tracks.isEmpty {
        tracks[0].collapse()
        tracks[tracks.count - 1].collapse()
    }
}
